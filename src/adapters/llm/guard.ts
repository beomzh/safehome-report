/**
 * LLM 이 쓴 문장에서 "안전을 보증하거나 승인·결과를 단정하는 표현"을 가려낸다.
 * 이 앱은 안전을 보증하지 않으므로(프롬프트도 같은 지시) 출력에서 한 번 더 코드로 거른다.
 * 부정형("안전하지 않습니다", "보장하지 않습니다")은 걸리지 않게 어미까지 맞춰 찾는다.
 */
const CLAIMS: RegExp[] = [
  /안전(합니다|해요|함|할 것|합니다만)/,
  /안전하다(?![고는며가])/,
  /(문제|위험|걱정)(이|은|가)?\s*(전혀\s*)?(없(습니다|다|어요|음)|없을 것)/,
  /(보증|보장)(합니다|됩니다|한다|돼요|됨)/,
  /(대출|승인|심사)(이|은|가)?\s*(확실히\s*)?(됩니다|될 것|가능합니다|문제없|통과합니다|통과할 것)/,
  /(계약|입주)(해도|하셔도)\s*(됩니다|좋습니다|문제없습니다|괜찮습니다)/,
  /100\s*%\s*(안전|보장|승인)/,
  /(반드시|틀림없이|확실히)\s*(안전|승인|돌려받)/,
  /돌려받을 수 있습니다/,
];

/** 단정 표현이 들어 있으면 true */
export function containsClaim(text: string): boolean {
  return CLAIMS.some((re) => re.test(text));
}
